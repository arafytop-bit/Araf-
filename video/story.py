def chg(el, at, dur=0.0, **kw): el.to(A(at), dur, **kw); return el
def hero(at, text, x=960, y=540, size=200, color=INK, **kw): return add("hero", at, x=x, y=y, text=text, size=size, color=color, **kw)
def typed(at, text, x=960, y=540, size=150, color=INK, cps=30, **kw):
    el = add("hero", at, x=x, y=y, text=text, size=size, color=color, chars=0, **kw)
