def label(at, text, x=70, y=110, size=66, color=RED):
    el = add("label", at, x=x, y=y, text=text, size=size, color=color, chars=0); el.to(el.t0, len(text) / 30, chars=len(text)); return el
def slide(el, dx=0, dy=0, dur=0.8):
    x, y = el.base["x"], el.base["y"]; el.base["x"] = x + dx; el.base["y"] = y + dy; el.to(el.t0, dur, x=x, y=y); return el
def scale_in(el, k0=2.5, dur=1.2):
    s = el.base["s"]; el.base["s"] = s * k0; el.to(el.t0, dur, s=s); return el
def push(el, k1=1.4, dur=2.2, at=None):
    t = A(at) if at else el.t0; el.to(t, dur, s=el.base["s"] * k1); return el
def fade(el, dur=0.12):
    el.base["op"] = 0.0; el.to(el.t0, dur, op=1.0); return el
def grow(el, prop="p", v0=0.0, v1=1.0, dur=0.8, at=None):
    el.base[prop] = v0; t = A(at) if at else el.t0; el.to(t, dur, **{prop: v1}); return el
def wipe(el, box, dur=0.7):
    el.base["wipe"] = 0.0; el.wipe_box = box; el.to(el.t0, dur, wipe=1.0); return el
def gone(el, at): el.t1 = A(at); return el
STING_GAP = 1.35
def chapter(at, text, color=RED, bg=WHITE):
    """Chapter label shown during the inserted sting pause before `at` (like the original's section stings)."""
    t = A(at) - STING_GAP + 0.1
    B.cut(t=t, bg=bg)
    el = B.add("label", t=t, x=70, y=110, text=text, size=66, color=color, chars=0); el.to(t, len(text) / 30, chars=len(text))
    return el
def typed_over(at, text, x=960, y=540, size=150, color=INK, **kw):
    """Typewriter text spread over the spoken duration of the anchor phrase."""
    t0 = A(at); t1 = B.words.end_of(at)
    el = B.add("hero", t=t0, x=x, y=y, text=text, size=size, color=color, chars=0, **kw)
    el.to(t0, max(0.2, t1 - t0), chars=len(text.replace("|", " "))); return el
def spin(el, deg=360, dur=3.0): el.to(el.t0, dur, rot=el.base["rot"] + deg); return el
def camto(sc, at, dur, x=960, y=540, s=1.0): sc.cam.to(A(at), dur, x=x, y=y, s=s)
def stagger(at, items, gap=2):
    """items: list of (kind, kw) popped gap frames apart starting at anchor."""
    t = A(at); els = []
    for i, (kind, kw) in enumerate(items): els.append(B.add(kind, t=t + i * gap / FPS, **kw))
    return els


def state_pt(name, w, city):
    import props as _p
    us = _p._us(); st = us["states"][name]; (bx0, by0), (bx1, by1) = st["bounds"]
    sc = w / (bx1 - bx0); cx, cy = (bx0 + bx1) / 2, (by0 + by1) / 2; px, py = us["cities"][city]
    return (px - cx) * sc, (py - cy) * sc

